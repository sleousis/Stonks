// Writes src/app/core/auth/route-permissions.gen.ts from the `x-permission`
// each route declares in openapi.json, so the console can hide actions the
// signed-in user may not take. Run by `npm run api:generate`; checked by
// `npm run api:check`. Never edit the output by hand.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/app/core/auth/route-permissions.gen.ts';

const spec = JSON.parse(readFileSync('openapi.json', 'utf8'));
const entries = [];
const permissions = new Set();
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const permission = op['x-permission'];
    if (!permission) continue;
    permissions.add(permission);
    entries.push([`${method.toUpperCase()} ${path}`, permission]);
  }
}
entries.sort(([a], [b]) => a.localeCompare(b));

const union = [...permissions]
  .sort()
  .map((p) => `  | '${p}'`)
  .join('\n');
const lines = [
  '// Generated by scripts/gen-permissions.mjs from openapi.json. Do not edit.',
  '',
  '/** Every permission a route in the API contract asks for. */',
  `export type RoutePermission =\n${union};`,
  '',
  '/** `"METHOD /api/path/{param}"` to the permission the route needs. */',
  'export const ROUTE_PERMISSIONS: Readonly<Record<string, RoutePermission>> = {',
  ...entries.map(([k, v]) => `  '${k}': '${v}',`),
  '};',
  '',
];
writeFileSync(OUT, lines.join('\n'));
execSync(`npx prettier --write ${OUT}`, { stdio: 'ignore' });
console.log(`Wrote ${entries.length} route permissions to ${OUT}.`);
